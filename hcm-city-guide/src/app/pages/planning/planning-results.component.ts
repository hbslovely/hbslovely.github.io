import { Component, OnInit } from '@angular/core';
import { CommonModule } from '@angular/common';
import { TranslateModule } from '@ngx-translate/core';
import { Router, NavigationExtras } from '@angular/router';
import { PlanningService, GeneratedPlan, PlanningData } from '@core/services/planning.service';

@Component({
  selector: 'app-planning-results',
  standalone: true,
  imports: [
    CommonModule,
    TranslateModule
  ],
  templateUrl: './planning-results.component.html',
  styleUrls: ['./planning-results.component.scss']
})
export class PlanningResultsComponent implements OnInit {
  plan: GeneratedPlan | null = null;
  loading = true;
  error: string | null = null;

  constructor(
    private router: Router,
    private planningService: PlanningService
  ) {}

  ngOnInit() {
    // Get planning data from router state
    const navigation = this.router.getCurrentNavigation();
    const planningData = navigation?.extras?.state?.['planningData'] as PlanningData;

    if (!planningData) {
      this.error = 'No planning data found. Please start over.';
      this.loading = false;
      return;
    }

    this.generatePlan(planningData);
  }

  private generatePlan(data: PlanningData) {
    this.loading = true;
    this.error = null;

    this.planningService.generatePlan(data).subscribe({
      next: (plan) => {
        this.plan = plan;
        this.loading = false;
      },
      error: (err) => {
        this.error = 'Failed to generate plan. Please try again.';
        this.loading = false;
        console.error('Error generating plan:', err);
      }
    });
  }

  startOver() {
    this.router.navigate(['/planning']);
  }

  sharePlan() {
    if (this.plan) {
      // In a real app, you would implement sharing functionality
      const shareText = `Check out my ${this.plan.title}! Generated by HCM City Guide.`;
      
      if (navigator.share) {
        navigator.share({
          title: this.plan.title,
          text: shareText,
          url: window.location.href
        });
      } else {
        // Fallback: copy to clipboard
        navigator.clipboard.writeText(shareText + ' ' + window.location.href);
        alert('Plan details copied to clipboard!');
      }
    }
  }

  downloadPlan() {
    if (this.plan) {
      // Generate PDF or text file
      const content = this.generatePlanText();
      const blob = new Blob([content], { type: 'text/plain' });
      const url = window.URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = `${this.plan!.title.replace(/\s+/g, '_')}.txt`;
      link.click();
      window.URL.revokeObjectURL(url);
    }
  }

  private generatePlanText(): string {
    if (!this.plan) return '';

    let content = `${this.plan.title}\n`;
    content += `${'='.repeat(this.plan.title.length)}\n\n`;
    content += `${this.plan.summary}\n\n`;
    content += `Total Duration: ${this.plan.totalDays} days\n`;
    content += `Estimated Cost: ${this.plan.totalCost}\n\n`;

    this.plan.days.forEach(day => {
      content += `Day ${day.day}: ${day.title}\n`;
      content += `${'-'.repeat(day.title.length + 8)}\n`;
      
      day.items.forEach(item => {
        content += `${item.time} - ${item.title}\n`;
        content += `   ${item.description}\n`;
        content += `   Location: ${item.location}\n`;
        content += `   Duration: ${item.duration}\n`;
        content += `   Cost: ${item.cost}\n\n`;
      });
      
      content += `Day Total: ${day.totalCost} | Duration: ${day.totalDuration}\n\n`;
    });

    content += `Recommendations:\n`;
    this.plan.recommendations.forEach(rec => {
      content += `• ${rec}\n`;
    });

    content += `\nTips:\n`;
    this.plan.tips.forEach(tip => {
      content += `• ${tip}\n`;
    });

    return content;
  }

  getItemIcon(type: string): string {
    switch (type) {
      case 'attraction': return 'fas fa-landmark';
      case 'restaurant': return 'fas fa-utensils';
      case 'hotel': return 'fas fa-hotel';
      case 'activity': return 'fas fa-star';
      case 'transport': return 'fas fa-bus';
      default: return 'fas fa-map-marker-alt';
    }
  }

  getCategoryColor(category: string): string {
    switch (category) {
      case 'historical': return '#8B5CF6';
      case 'cultural': return '#F59E0B';
      case 'food': return '#EF4444';
      case 'nature': return '#10B981';
      case 'shopping': return '#3B82F6';
      case 'entertainment': return '#EC4899';
      default: return '#6B7280';
    }
  }
}
